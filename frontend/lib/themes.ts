export const DEFAULT_LIGHT_THEME: ThemeName = "Default Light";
export const DEFAULT_DARK_THEME: ThemeName = "Default Dark";

export function getThemeByName(name?: string | null, fallback: ThemeName = DEFAULT_LIGHT_THEME): ThemePalette {
    if (name) {
        const lower = name.trim().toLowerCase();
        const found = THEME_LIST.find((t) => t.name.toLowerCase() === lower);
        if (found) return found;
    }
    return THEME_LIST.find((t) => t.name === fallback) || THEME_LIST[0];
}

export function getThemeCssVars(theme: ThemePalette): Record<string, string> {
    return {
        "--theme-body-bg": theme.bodyBg,
        "--theme-topo-rgb": theme.topoRgba,
        "--theme-rail-bg": theme.railBg,
        "--theme-rail-active": theme.railActive,
        "--theme-rail-text": theme.railText,
        "--theme-surface-primary": theme.surfacePrimary,
        "--theme-surface-primary-rgb": theme.surfacePrimaryRgb,
        "--theme-surface-focus": theme.surfaceFocus,
        "--theme-surface-hover-white": theme.surfaceHoverWhite,
        "--theme-surface-secondary": theme.surfaceSecondary,
        "--theme-surface-tertiary": theme.surfaceTertiary,
        "--theme-surface-interactive": theme.surfaceInteractive,
        "--theme-surface-tinted": theme.surfaceTinted,
        "--theme-hover-subtle": theme.hoverSubtle,
        "--theme-hover-strong": theme.hoverStrong,
        "--theme-border": theme.border,
        "--theme-text-primary": theme.textPrimary,
        "--theme-text-primary-hover": theme.textPrimaryHover,
        "--theme-text-secondary": theme.textSecondary,
        "--theme-text-muted": theme.textMuted,
        "--theme-text-placeholder": theme.textPlaceholder,
        "--theme-accent": theme.accent,
        "--theme-accent-hover": theme.accentHover,
        "--theme-accent-rgb": theme.accentRgb,
        "--alpaca-dark": theme.railBg,
        "--alpaca-primary": theme.accent,
        "--alpaca-light": theme.surfaceSecondary,
        "--alpaca-border": theme.border,
        "--alpaca-bubble": theme.surfaceInteractive,
    };
}

export function applyThemeToDocument(theme: ThemePalette): void {
    if (typeof document === "undefined") return;
    const root = document.documentElement;
    const vars = getThemeCssVars(theme);
    for (const [k, v] of Object.entries(vars)) {
        root.style.setProperty(k, v);
    }
    root.classList.toggle("dark", theme.isDark);
    root.setAttribute("data-theme", theme.isDark ? "dark" : "light");
    root.setAttribute("data-theme-preset", theme.name);
    const isCustom = theme.name !== "Default Light";
    if (isCustom) {
        root.setAttribute("data-custom-theme", "true");
    } else {
        root.removeAttribute("data-custom-theme");
    }
    try {
        localStorage.setItem(
            "walpaca_active_theme_cache",
            JSON.stringify({
                name: theme.name,
                isDark: theme.isDark,
                vars,
            })
        );
    } catch {
        // ignore storage errors
    }
}
